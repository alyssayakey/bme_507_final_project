def make_model(iso=0.0, celltype=1):
    # Isolated globals per model: cell-type changes cannot overwrite other instances.
    g = ephys.__globals__.copy()
    g.update(initialize_constants(celltype, 1))
    from types import FunctionType
    electrical = FunctionType(ephys.__code__, g)
    c = constants(iso)
    def rhs(t, y, stimulus=0.0):
        settings = effective(y, SimpleNamespace(const_signaling=c))
        pp_sum = c.pp1_K - c.PP1_cyt + y[96]
        pp_free = 0.5*(np.sqrt(pp_sum**2 + 4*c.pp1_K*c.PP1_cyt)-pp_sum)
        settings.Whole_cell_PP1 = (c.PP1_cav/c.vr_cav + c.PP1_eca/c.vr_eca + pp_free/c.vr_cyt)
        return np.r_[electrical(t, y[:58], stimulus, settings), signaling(t,y[58:],c)]
    return rhs, c

def prepare_state(iso=0.0, seconds=10000):
    y = initial_state()
    c = constants(iso)
    sol = solve_ivp(lambda t,x: signaling(t,x,c), (0,seconds*1000), y[58:],
                    method='BDF', rtol=1e-6, atol=1e-9)
    if not sol.success: raise RuntimeError(sol.message)
    y[58:] = sol.y[:,-1]
    return y

def run_cell(iso=0.0, beats=5, pcl=1000.0, state=None, rtol=1e-6, atol=1e-9):
    """Fully coupled 115-state run. Signaling is preconditioned; electrical states are not.
    Returns the LAST beat, final state, and per-beat APD90/amplitude diagnostics.
    Few-beat runs are operational checks, not steady-state validation.
    """
    rhs,c = make_model(iso)
    y = prepare_state(iso) if state is None else np.array(state, dtype=float, copy=True)
    history=[]
    for beat in range(beats):
        ts=[];ys=[]
        for start,end,stim in [(0,10,0),(10,10.5,-80),(10.5,pcl,0)]:
            grid=np.unique(np.r_[start,np.arange(np.ceil(start),end,1),end])
            sol=solve_ivp(lambda t,x:rhs(t,x,stim),(start,end),y,method='BDF',
                          rtol=rtol,atol=atol,t_eval=grid)
            if not sol.success: raise RuntimeError(sol.message)
            y=sol.y[:,-1]
            ts.extend(sol.t if not ts else sol.t[1:])
            ys.extend(sol.y.T if not ys else sol.y.T[1:])
        t=np.array(ts); states=np.array(ys); v=states[:,0]
        # Interpolated 90% repolarization crossing measured from stimulus onset (10 ms).
        peak=int(np.argmax(v)); threshold=v[0]+0.1*(v[peak]-v[0])
        crossings=np.where((v[peak:-1]>threshold)&(v[peak+1:]<=threshold))[0]
        apd=np.nan
        if crossings.size and v[peak]>0:
            k=peak+crossings[0]
            crossing=t[k]+(threshold-v[k])*(t[k+1]-t[k])/(v[k+1]-v[k])
            apd=crossing-10
        history.append([beat+1,apd,(states[:,5].max()-states[:,5].min())*1000])
    return {'time':t,'voltage':states[:,0],'calcium_uM':states[:,5]*1000,
            'state':y.copy(),'history':np.array(history),'states':states}
